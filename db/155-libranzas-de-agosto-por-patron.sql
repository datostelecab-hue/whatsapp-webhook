--     día de la semana es de descanso si libró la mayoría de las veces que se
--     vio, y al menos dos: con una sola semana no hay patrón.
--   · Los días: del 25/08 al 02/09, dentro de su alta, sin horas, sin J, sin
--     vacaciones/baja/permiso y sin libranza puesta, que caen en su patrón.
-- Salieron 223 días en 116 personas. 96 personas con «Ausencias» esos días no tienen
-- patrón (bajas de primeros de septiembre, gente sin plaza): esas no se tocan.
--
-- Se ponen como libranza A MANO (bitacora_dia, marca 'L'), firmadas por Camilo
-- (usuario 7), igual que si se hubiera pulsado «Era libranza» en cada día. Se
-- quitan con «Quitar la libranza» si alguna está mal. Solo si el día sigue
-- sin nada: ni una marca puesta ni horas selladas.

